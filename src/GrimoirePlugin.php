<?php

declare(strict_types=1);

namespace BlackpigCreatif\Grimoire;

use BlackpigCreatif\Grimoire\Facades\Grimoire;
use BlackpigCreatif\Grimoire\Filament\Clusters\GrimoireDocumentationCluster;
use BlackpigCreatif\Grimoire\Filament\Clusters\GrimoireTomeCluster;
use BlackpigCreatif\Grimoire\Filament\Pages\GrimoireChapterPage;
use BlackpigCreatif\Grimoire\Services\TomeRegistry;
use Closure;
use Filament\Contracts\Plugin;
use Filament\Panel;
use ReflectionClass;
use Symfony\Component\Finder\Finder;

class GrimoirePlugin implements Plugin
{
    protected string $navigationGroup = '';

    protected string $theme = '';

    /**
     * Whether to register Grimoire's own built-in self-documentation Tome.
     * Off by default — opt in with ->withDocs().
     * A Closure receives the authenticated user and must return bool.
     *
     * @var bool|Closure(mixed): bool
     */
    protected bool | Closure $withDocs = false;

    /**
     * Host-app Tome IDs to register in this panel. Null registers every Tome found.
     *
     * @var list<string>|null
     */
    protected ?array $tomes = null;

    public function getId(): string
    {
        return 'grimoire';
    }

    public static function make(): static
    {
        return app(static::class);
    }

    public static function get(): static
    {
        /** @var static $plugin */
        $plugin = filament(app(static::class)->getId());

        return $plugin;
    }

    /**
     * Override the navigation group label.
     */
    public function navigationGroup(string $label): static
    {
        $this->navigationGroup = $label;

        return $this;
    }

    /**
     * Limit this panel to the given host-app Tomes (those generated by grimoire:make-tome).
     * Tomes shipped by other packages are controlled by their own plugins, and Grimoire's
     * own documentation by withDocs().
     *
     * @param  list<string>  $tomeIds
     */
    public function tomes(array $tomeIds): static
    {
        $this->tomes = array_values($tomeIds);

        return $this;
    }

    /**
     * @return list<string>|null
     */
    public function getTomes(): ?array
    {
        return $this->tomes;
    }

    /**
     * Set a custom prose theme CSS class to append to the chapter wrapper.
     */
    public function theme(string $cssClass): static
    {
        $this->theme = $cssClass;

        return $this;
    }

    /**
     * Register Grimoire's own built-in self-documentation Tome in this panel.
     *
     * Accepts a bool or a Closure that receives the authenticated user and returns bool.
     * The Closure is evaluated at request time (inside canAccess()), so auth() is available.
     *
     * Examples:
     *   ->withDocs()                                    // always shown
     *   ->withDocs(fn ($user) => $user->isSuperAdmin()) // shown only to superadmins
     *   ->withDocs(app()->isLocal())                    // shown only in local environment
     *
     * @param  bool|Closure(mixed): bool  $condition
     */
    public function withDocs(bool | Closure $condition = true): static
    {
        $this->withDocs = $condition;

        return $this;
    }

    /**
     * Evaluate the withDocs condition against the given user.
     * Called from GrimoireDocumentationCluster::canAccess().
     */
    public function shouldShowDocs(mixed $user): bool
    {
        if ($this->withDocs instanceof Closure) {
            return (bool) ($this->withDocs)($user);
        }

        return $this->withDocs;
    }

    public function register(Panel $panel): void
    {
        $group = $this->navigationGroup ?: config('grimoire.navigation_group', 'Help');
        $theme = $this->theme ?: config('grimoire.theme', '');

        // Merge plugin-level overrides into config so pages and clusters can read them.
        config([
            'grimoire.navigation_group' => $group,
            'grimoire.theme' => $theme,
        ]);

        if ($this->withDocs !== false) {
            // The registry is app-wide but register() runs once per panel, so only the
            // first panel with ->withDocs() registers the Tome.
            if (app(TomeRegistry::class)->find('grimoire') === null) {
                Grimoire::registerTome(
                    id: 'grimoire',
                    label: 'Grimoire Documentation',
                    icon: 'heroicon-o-book-open',
                    path: dirname(__DIR__) . '/resources/grimoire/getting-started',
                    clusterClass: GrimoireDocumentationCluster::class,
                    slug: 'grimoire',
                );
            }

            // Discover the built-in Cluster and Chapter Page stubs from inside the package.
            $panel->discoverClusters(
                in: __DIR__ . '/Filament/Clusters',
                for: 'BlackpigCreatif\\Grimoire\\Filament\\Clusters',
            );

            $panel->discoverPages(
                in: __DIR__ . '/Filament/Pages',
                for: 'BlackpigCreatif\\Grimoire\\Filament\\Pages',
            );
        }

        // Host-app stubs generated by grimoire:make-tome and grimoire:make-chapter.
        foreach ($this->getHostDirectories() as $directory => $namespace) {
            if (! is_dir($directory)) {
                continue;
            }

            if ($this->tomes === null) {
                $panel->discoverClusters(in: $directory, for: $namespace);
                $panel->discoverPages(in: $directory, for: $namespace);

                continue;
            }

            $panel->pages($this->discoverHostComponentsForTomes($directory, $namespace));
        }
    }

    /**
     * Directories holding host-app Tome stubs, keyed by path, valued by namespace.
     *
     * @return array<string, string>
     */
    protected function getHostDirectories(): array
    {
        return [
            app_path('Filament/Grimoire/Clusters') => 'App\\Filament\\Grimoire\\Clusters',
            app_path('Filament/Grimoire/Pages') => 'App\\Filament\\Grimoire\\Pages',
        ];
    }

    /**
     * Find the Tome Cluster and Chapter Page stubs in a directory that belong to
     * one of the Tomes given to tomes().
     *
     * @return array<class-string>
     */
    protected function discoverHostComponentsForTomes(string $directory, string $namespace): array
    {
        $components = [];

        foreach (Finder::create()->files()->in($directory)->name('*.php') as $file) {
            $class = $namespace . '\\' . str_replace(['/', '.php'], ['\\', ''], $file->getRelativePathname());

            if (! class_exists($class) || (new ReflectionClass($class))->isAbstract()) {
                continue;
            }

            if (! is_subclass_of($class, GrimoireTomeCluster::class) && ! is_subclass_of($class, GrimoireChapterPage::class)) {
                continue;
            }

            if (in_array($class::$tomeId, $this->tomes, strict: true)) {
                $components[] = $class;
            }
        }

        return $components;
    }

    public function boot(Panel $panel): void
    {
        //
    }
}
